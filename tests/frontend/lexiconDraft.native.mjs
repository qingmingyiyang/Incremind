import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { beginLexiconDraft, editLexiconDraft, lexiconDraftOperations, reconcileLexiconDraft, reviewLexiconDraft } from '../../src/frontend/src/features/settings/lexiconDraft.js';

const input = JSON.parse(await readFile(process.argv[2], 'utf8'));
const original = JSON.stringify(input);
const first = input.before.terms.find(term => term.term === '甲词');
let draft = editLexiconDraft(beginLexiconDraft(first, input.before.revision), { name: '输入甲', weight: 5 });
draft = reconcileLexiconDraft(draft, input.afterB.terms.find(term => term.id === first.id), input.afterB.revision);
assert.equal(draft.name, '输入甲');
assert.equal(draft.weight, 5);
assert.equal(draft.dirty, true);
assert.equal(draft.stale, true);
assert.equal(draft.conflict, false);
assert.throws(() => lexiconDraftOperations(draft, 'preview'), /requires_review/);
draft = reconcileLexiconDraft(draft, input.afterA.terms.find(term => term.id === first.id), input.afterA.revision);
assert.equal(draft.name, '输入甲');
assert.equal(draft.weight, 5);
assert.equal(draft.conflict, true);
const current = reviewLexiconDraft(draft, 'current');
assert.equal(current.name, '甲词');
assert.equal(current.weight, 2);
assert.equal(current.dirty, false);
const kept = reviewLexiconDraft(draft, 'keep');
assert.equal(kept.name, '输入甲');
assert.equal(kept.weight, 5);
assert.equal(kept.base.revision, input.afterA.revision);
assert.equal(kept.stale, false);
assert.equal(kept.conflict, false);
assert.deepEqual(lexiconDraftOperations(kept, 'preview'), [{ action: 'rename', term: '甲词', new_term: '输入甲', weight: 5 }]);
assert.equal(JSON.stringify(input), original);
process.stdout.write(JSON.stringify({ operations: lexiconDraftOperations(kept, 'preview'), expected_revision: kept.base.revision }));
